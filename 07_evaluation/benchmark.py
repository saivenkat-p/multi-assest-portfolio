# Benchmark Evaluator
# =============================================================================
class BenchmarkEvaluator:
    """
    Evaluates and benchmarks classical and quantum portfolio solvers.
    The evaluator computes a common optimization objective for each
    solver output, enabling direct comparison across optimization
    strategies.
    Attributes:
    risk_aversion:
    Risk-aversion coefficient used in the objective function.
    mvo:
    MeanVarianceObjective instance used for objective
    evaluation.
    """
    def __init__(
        self,
        risk_aversion: float = DEFAULT_RISK_AVERSION,
    ) -> None:
        """
        Initialize the benchmark evaluator.
        Args:
        risk_aversion:
        Risk-aversion coefficient used during objective
        evaluation.
        Raises:
        RuntimeError:
        If the objective function cannot be initialized.
        """
        logger.info("Initializing BenchmarkEvaluator.")
        if not np.isfinite(risk_aversion):
            raise ValueError("risk_aversion must be finite.")
        
        self.risk_aversion = float(risk_aversion)
        
        if MeanVarianceObjective is None:
            raise RuntimeError(
                "MeanVarianceObjective could not be imported."
            )
            
        self.mvo = MeanVarianceObjective(
            risk_aversion=self.risk_aversion
        )
        logger.info(
            "BenchmarkEvaluator initialized successfully."
        )

    # -------------------------------------------------------------------------
    # Validation Helpers
    # -------------------------------------------------------------------------
    @staticmethod
    def _validate_covariance_matrix(
        covariance_matrix: np.ndarray,
    ) -> None:
        """
        Validate the covariance matrix.
        Args:
        covariance_matrix:
        Covariance matrix.
        Raises:
        ValueError:
        If validation fails.
        """
        if covariance_matrix.ndim != 2:
            raise ValueError(
                "Covariance matrix must be two-dimensional."
            )
        rows, cols = covariance_matrix.shape
        if rows != cols:
            raise ValueError(
                "Covariance matrix must be square."
            )
        if not np.all(np.isfinite(covariance_matrix)):
            raise ValueError(
                "Covariance matrix contains NaN or Inf."
            )
        if not np.allclose(
            covariance_matrix,
            covariance_matrix.T,
            atol=FLOAT_TOLERANCE,
        ):
            raise ValueError(
                "Covariance matrix must be symmetric."
            )

    @staticmethod
    def _validate_weights_dictionary(
        weights: Dict[str, np.ndarray],
        asset_count: int,
    ) -> None:
        """
        Validate solver weight dictionary.
        Args:
        weights:
        Dictionary containing portfolio allocations.
        asset_count:
        Expected number of assets.
        Raises:
        ValueError:
        If validation fails.
        """
        if not isinstance(weights, dict):
            raise TypeError(
                "Weights must be provided as a dictionary."
            )
        for solver_name, allocation in weights.items():
            if allocation is None:
                raise ValueError(
                    f"{solver_name} returned None."
                )
            allocation = np.asarray(
                allocation,
                dtype=float,
            )
            if allocation.ndim != 1:
                raise ValueError(
                    f"{solver_name} weights must be 1-D."
                )
            if allocation.size != asset_count:
                raise ValueError(
                    f"{solver_name} asset dimension mismatch."
                )
            if not np.all(np.isfinite(allocation)):
                raise ValueError(
                    f"{solver_name} contains NaN or Inf."
                )

    def _validate_inputs(
        self,
        expected_returns: np.ndarray,
        covariance_matrix: np.ndarray,
        quantum_weights: Dict[str, np.ndarray],
        classical_weights: Dict[str, np.ndarray],
    ) -> None:
        """
        Validate all public API inputs.
        Args:
        expected_returns:
        Expected asset returns.
        covariance_matrix:
        Asset covariance matrix.
        quantum_weights:
        Quantum solver allocations.
        classical_weights:
        Classical solver allocations.
        """
        expected_returns = np.asarray(
            expected_returns,
            dtype=float,
        )
        if expected_returns.ndim != 1:
            raise ValueError(
                "Expected returns must be one-dimensional."
            )
        if not np.all(np.isfinite(expected_returns)):
            raise ValueError(
                "Expected returns contain NaN or Inf."
            )
            
        self._validate_covariance_matrix(
            covariance_matrix
        )
        
        asset_count = expected_returns.size
        if covariance_matrix.shape[0] != asset_count:
            raise ValueError(
                "Covariance matrix dimension mismatch."
            )
            
        self._validate_weights_dictionary(
            classical_weights,
            asset_count,
        )
        self._validate_weights_dictionary(
            quantum_weights,
            asset_count,
        )
        logger.info("Input validation completed successfully.")

    # -------------------------------------------------------------------------
    # Numerical Helpers
    # -------------------------------------------------------------------------
    @staticmethod
    def _cleanup_scalar(value: float) -> float:
        """
        Clean numerical artifacts from a scalar.
        Args:
        value:
        Numerical value.
        Returns:
        Cleaned floating-point value.
        Raises:
        ValueError:
        If the value is not finite.
        """
        if not np.isfinite(value):
            raise ValueError("Objective value is not finite.")
        if np.isclose(value, 0.0, atol=FLOAT_TOLERANCE):
            return 0.0
        return float(value)

    # -------------------------------------------------------------------------
    # Internal Evaluation Helpers
    # -------------------------------------------------------------------------
    def _evaluate_single_solver(
        self,
        solver_name: str,
        weights: np.ndarray,
        expected_returns: np.ndarray,
        covariance_matrix: np.ndarray,
    ) -> Optional[float]:
        """
        Evaluate a single solver allocation.
        Args:
        solver_name:
        Solver identifier.
        weights:
        Portfolio allocation.
        expected_returns:
        Expected asset returns.
        covariance_matrix:
        Asset covariance matrix.
        Returns:
        Objective value if successful, otherwise None.
        """
        logger.info(
            "Evaluating solver '%s'.",
            solver_name,
        )
        try:
            objective_value = self.mvo.calculate_objective(
                weights,
                expected_returns,
                covariance_matrix,
            )
            objective_value = self._cleanup_scalar(
                objective_value
            )
            logger.info(
                "Solver '%s' objective = %.10f",
                solver_name,
                objective_value,
            )
            return objective_value
        except Exception:
            logger.exception(
                "Evaluation failed for solver '%s'.",
                solver_name,
            )
            return None

    def _evaluate_collection(
        self,
        weights_dictionary: Dict[str, np.ndarray],
        expected_returns: np.ndarray,
        covariance_matrix: np.ndarray,
    ) -> Dict[str, Optional[float]]:
        """
        Evaluate every solver contained in a dictionary.
        Args:
        weights_dictionary:
        Mapping from solver name to portfolio weights.
        expected_returns:
        Expected returns.
        covariance_matrix:
        Covariance matrix.
        Returns:
        Dictionary mapping solver names to objective values.
        """
        logger.info(
            "Evaluating %d solver(s).",
            len(weights_dictionary),
        )
        results: Dict[str, Optional[float]] = {}
        successful = 0
        failed = 0
        
        for solver_name, weights in weights_dictionary.items():
            objective = self._evaluate_single_solver(
                solver_name=solver_name,
                weights=weights,
                expected_returns=expected_returns,
                covariance_matrix=covariance_matrix,
            )
            results[solver_name] = objective
            if objective is None:
                failed += 1
            else:
                successful += 1
                
        logger.info(
            "Evaluation complete. Successful=%d Failed=%d",
            successful,
            failed,
        )
        return results

    # -------------------------------------------------------------------------
    # Benchmark Utilities
    # -------------------------------------------------------------------------
    @staticmethod
    def _compute_optimality_gaps(
        objective_values: Dict[str, Optional[float]],
        reference_solver: str = REFERENCE_SOLVER,
    ) -> Dict[str, Optional[float]]:
        """
        Compute optimality gaps relative to the reference solver.
        Gap = Objective - Reference Objective
        Lower values indicate solutions closer to the reference optimum.
        Args:
        objective_values:
        Objective values for every solver.
        reference_solver:
        Reference solver used as the benchmark.
        Returns:
        Dictionary containing optimality gaps.
        """
        logger.info(
            "Computing optimality gaps using '%s'.",
            reference_solver,
        )
        reference_value = objective_values.get(
            reference_solver
        )
        gaps: Dict[str, Optional[float]] = {}
        
        if reference_value is None:
            logger.warning(
                "Reference solver '%s' unavailable.",
                reference_solver,
            )
            for solver in objective_values:
                gaps[solver] = None
            return gaps
            
        for solver, objective in objective_values.items():
            if objective is None:
                gaps[solver] = None
                continue
            gap = objective - reference_value
            gaps[solver] = BenchmarkEvaluator._cleanup_scalar(
                gap
            )
            
        logger.info(
            "Optimality gap computation completed."
        )
        return gaps

    @staticmethod
    def _generate_metadata(
        objective_values: Dict[str, Optional[float]],
        execution_time: float,
    ) -> Dict[str, Any]:
        """
        Generate benchmark execution metadata.
        Args:
        objective_values:
        Computed objective values.
        execution_time:
        Benchmark runtime in seconds.
        Returns:
        Metadata dictionary.
        """
        successful = sum(
            value is not None
            for value in objective_values.values()
        )
        failed = len(objective_values) - successful
        
        return {
            "report_version": REPORT_VERSION,
            "solver_count": len(objective_values),
            "successful_evaluations": successful,
            "failed_evaluations": failed,
            "execution_time_seconds": execution_time,
        }

    # -------------------------------------------------------------------------
    # Public API
    # -------------------------------------------------------------------------
    def run_benchmark(
        self,
        expected_returns: np.ndarray,
        covariance_matrix: np.ndarray,
        quantum_weights: Dict[str, np.ndarray],
        classical_weights: Dict[str, np.ndarray],
    ) -> Dict[str, Any]:
        """
        Execute the benchmark across all classical and quantum solvers.
        Every portfolio allocation is evaluated using the common
        Mean-Variance objective function. The resulting objective values
        are compared against the reference solver to compute optimality
        gaps.
        Args:
        expected_returns:
        One-dimensional expected asset returns.
        covariance_matrix:
        Square covariance matrix.
        quantum_weights:
        Dictionary mapping quantum solver names to portfolio
        allocations.
        classical_weights:
        Dictionary mapping classical solver names to portfolio
        allocations.
        Returns:
        Production benchmark report.
        Raises:
        RuntimeError:
        If benchmark execution fails.
        """
        logger.info("=" * 70)
        logger.info("Starting benchmark evaluation.")
        logger.info("=" * 70)
        start_time = time.perf_counter()
        
        try:
            # --------------------------------------------------------------
            # Validate Inputs
            # --------------------------------------------------------------
            self._validate_inputs(
                expected_returns=expected_returns,
                covariance_matrix=covariance_matrix,
                quantum_weights=quantum_weights,
                classical_weights=classical_weights,
            )
            
            # --------------------------------------------------------------
            # Evaluate Classical Solvers
            # --------------------------------------------------------------
            logger.info("Evaluating classical solvers...")
            classical_results = self._evaluate_collection(
                weights_dictionary=classical_weights,
                expected_returns=expected_returns,
                covariance_matrix=covariance_matrix,
            )
            
            # --------------------------------------------------------------
            # Evaluate Quantum Solvers
            # --------------------------------------------------------------
            logger.info("Evaluating quantum solvers...")
            quantum_results = self._evaluate_collection(
                weights_dictionary=quantum_weights,
                expected_returns=expected_returns,
                covariance_matrix=covariance_matrix,
            )
            
            # --------------------------------------------------------------
            # Merge Results
            # --------------------------------------------------------------
            objective_values: Dict[str, Optional[float]] = {
                **classical_results,
                **quantum_results,
            }
            logger.info(
                "Successfully evaluated %d solver(s).",
                len(objective_values),
            )
            
            # --------------------------------------------------------------
            # Compute Optimality Gaps
            # --------------------------------------------------------------
            optimality_gaps = self._compute_optimality_gaps(
                objective_values=objective_values,
                reference_solver=REFERENCE_SOLVER,
            )
            
            # --------------------------------------------------------------
            # Runtime Statistics
            # --------------------------------------------------------------
            execution_time = (
                time.perf_counter() - start_time
            )
            metadata = self._generate_metadata(
                objective_values=objective_values,
                execution_time=execution_time,
            )
            
            # --------------------------------------------------------------
            # Final Report
            # --------------------------------------------------------------
            report: Dict[str, Any] = {
                "objective_values": objective_values,
                "optimality_gaps": optimality_gaps,
                "ground_truth_solver": REFERENCE_SOLVER,
                "risk_aversion_used": self.risk_aversion,
                "metadata": metadata,
            }
            
            logger.info(
                "Benchmark completed successfully "
                "in %.6f seconds.",
                execution_time,
            )
            logger.info("=" * 70)
            return report
            
        except Exception as exc:
            logger.exception(
                "Benchmark evaluation failed."
            )
            raise RuntimeError(
                "Failed to execute benchmark evaluation."
            ) from exc

