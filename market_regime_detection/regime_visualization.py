"""
Module: 02_market_regime_detection.regime_visualization

Generates plots overlaying detected market regimes on financial time series.
"""

from __future__ import annotations

import logging
from typing import Mapping, Optional

import matplotlib.patches as mpatches
import matplotlib.pyplot as plt
import pandas as pd

logger = logging.getLogger(__name__)

# ============================================================================
# Module Constants
# ============================================================================

DEFAULT_FIGSIZE = (14, 7)
DEFAULT_ALPHA = 0.20

DEFAULT_COLOR_MAP = {
    "Bull": "green",
    "Bear": "red",
    "Stable": "blue",
    "High Volatility": "orange",
}


# ============================================================================
# Validation
# ============================================================================

def _validate_inputs(
    time_series: pd.Series,
    regime_labels: pd.Series,
) -> None:
    """
    Validate inputs for regime visualization.

    Args:
        time_series:
            Financial time series.

        regime_labels:
            Market regime labels.

    Raises:
        TypeError:
            If inputs are not pandas Series.

        ValueError:
            If inputs are empty, contain missing values,
            have duplicate indices, mismatched indices,
            or invalid data.
    """

    if not isinstance(time_series, pd.Series):
        raise TypeError("time_series must be a pandas Series.")

    if not isinstance(regime_labels, pd.Series):
        raise TypeError("regime_labels must be a pandas Series.")

    if time_series.empty:
        raise ValueError("time_series cannot be empty.")

    if regime_labels.empty:
        raise ValueError("regime_labels cannot be empty.")

    if not isinstance(time_series.index, pd.DatetimeIndex):
        raise TypeError("time_series index must be a DatetimeIndex.")

    if not isinstance(regime_labels.index, pd.DatetimeIndex):
        raise TypeError("regime_labels index must be a DatetimeIndex.")

    if time_series.index.has_duplicates:
        raise ValueError("time_series index contains duplicate values.")

    if regime_labels.index.has_duplicates:
        raise ValueError("regime_labels index contains duplicate values.")

    if time_series.isna().any():
        raise ValueError("time_series contains missing values.")

    if regime_labels.isna().any():
        raise ValueError("regime_labels contains missing values.")

    if not pd.api.types.is_numeric_dtype(time_series):
        raise TypeError("time_series must contain numeric values.")

    if len(time_series) != len(regime_labels):
        raise ValueError(
            "time_series and regime_labels must have equal length."
        )

    if not time_series.index.equals(regime_labels.index):
        raise ValueError(
            "time_series and regime_labels must share identical indices."
        )


# ============================================================================
# Visualization
# ============================================================================

def plot_regimes(
    time_series: pd.Series,
    regime_labels: pd.Series,
    title: str = "Market Regimes Overlaid on Asset Performance",
    color_map: Optional[Mapping[str, str]] = None,
) -> plt.Figure:
    """
    Plot a financial time series with background shading indicating
    detected market regimes.

    Args:
        time_series:
            Financial time series such as prices or cumulative returns.

        regime_labels:
            Semantic regime labels generated by the MarketClassifier.

        title:
            Plot title.

        color_map:
            Optional mapping between regime names and colors.

    Returns:
        matplotlib.figure.Figure:
            Generated matplotlib figure.

    Raises:
        TypeError:
            If the inputs have invalid types.

        ValueError:
            If validation fails.
    """

    logger.info("Generating regime visualization.")

    _validate_inputs(time_series, regime_labels)

    if color_map is None:
        color_map = DEFAULT_COLOR_MAP

    # Combine validated inputs
    df = pd.concat([time_series, regime_labels], axis=1)

    ts_col = df.columns[0]
    regime_col = df.columns[1]

    fig, ax = plt.subplots(figsize=DEFAULT_FIGSIZE)

    # ------------------------------------------------------------------
    # Plot primary series
    # ------------------------------------------------------------------

    ax.plot(
        df.index,
        df[ts_col],
        color="black",
        linewidth=1.5,
        label=ts_col,
    )

    # ------------------------------------------------------------------
    # Compute contiguous regime blocks
    # ------------------------------------------------------------------

    regime_shift = df[regime_col] != df[regime_col].shift(1)
    block_ids = regime_shift.cumsum()

    # ------------------------------------------------------------------
    # Shade regimes
    # ------------------------------------------------------------------

    for _, group in df.groupby(block_ids):

        start_date = group.index[0]
        end_date = group.index[-1]
        regime = group[regime_col].iloc[0]

        if regime not in color_map:
            logger.warning(
                "Unknown regime '%s'. Using grey shading.",
                regime,
            )

        color = color_map.get(regime, "grey")

        ax.axvspan(
            start_date,
            end_date,
            color=color,
            alpha=DEFAULT_ALPHA,
            lw=0,
        )

    # ------------------------------------------------------------------
    # Legend
    # ------------------------------------------------------------------

    legend_handles = [
        plt.Line2D(
            [0],
            [0],
            color="black",
            lw=1.5,
            label=ts_col,
        )
    ]

    for regime, color in color_map.items():

        if regime in df[regime_col].unique():

            legend_handles.append(
                mpatches.Patch(
                    color=color,
                    alpha=0.30,
                    label=regime,
                )
            )

    ax.legend(handles=legend_handles, loc="upper left")

    # ------------------------------------------------------------------
    # Formatting
    # ------------------------------------------------------------------

    ax.set_title(title, fontsize=16, fontweight="bold")
    ax.set_xlabel("Date")
    ax.set_ylabel("Value")

    ax.grid(True, linestyle="--", alpha=0.5)

    fig.tight_layout()

    logger.info("Regime visualization generated successfully.")

    return fig